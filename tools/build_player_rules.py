#!/usr/bin/env python3
"""Build the player's offline reference from the canonical v0.10 manuscript."""
from pathlib import Path
import hashlib
import json
import re
import sys
ROOT = Path(__file__).resolve().parents[1]
SOURCES = ['seed.md', '02_character_backgrounds.md', 'docs/PREGENS.md']
source = {name: (ROOT / name).read_text() for name in SOURCES}
roles = {}
for block in re.split(r'^## ', source[SOURCES[1]], flags=re.M)[1:]:
    role = block.splitlines()[0]
    if role not in ['Guide', 'Doctor', 'Hunter', 'Teamster']:
        continue
    entries = re.findall(r'^- \*\*(.+?):\*\* (.+)$', block, re.M)
    assert len(entries) == 8, f'{role}: expected 4 backgrounds and 4 techniques'
    roles[role] = {'backgrounds': dict(entries[:4]), 'techniques': dict(entries[4:])}
for row in source['seed.md'].splitlines():
    cells = [x.strip() for x in row.strip('|').split('|')]
    match = re.fullmatch(r'(Guide|Doctor|Hunter|Teamster) \((\w+)\)', cells[0])
    if match:
        role, primary = match.groups()
        roles[role].update(primary=primary, service=cells[1], intervention=cells[2])
pregens = []
for block in re.split(r'^## ', source['docs/PREGENS.md'], flags=re.M)[1:]:
    match = re.match(r'(.+) — (Guide|Doctor|Hunter|Teamster)\n', block)
    if not match:
        continue
    name, role = match.groups()
    score_row = next(line for line in block.splitlines() if re.match(r'^\| \d+ \(', line))
    scores = [int(x) for x in re.findall(r'(\d+) \([+−-]\d+\)', score_row)]
    assert sorted(scores) == [8, 10, 10, 12, 13, 15]
    labels = dict(re.findall(r'\*\*([^*]+):\*\* (.*?)(?= \*\*|\n|$)', block))
    background = labels['Background'].split('.')[0]
    assert background in roles[role]['backgrounds']
    pregens.append({'name': name, 'role': role, 'background': background,
                    'scores': dict(zip(['STR','DEX','CON','INT','WIS','CHA'], scores)),
                    'personal': {key.lower(): labels.get(key, '') for key in
                                 ['Dream','Promise','Boundary','Bond','Keepsake','Cargo','Voice','Reserve','Opening question','On the road']}})
assert len(pregens) == 4
conditions = {}
for row in source['seed.md'].splitlines():
    cells = [x.strip() for x in row.strip('|').split('|')]
    if len(cells) == 4 and re.match(r'^\d+ / \d+$', cells[2]):
        dc, marks = map(int, cells[2].split(' / '))
        conditions[cells[1]] = {'dc': dc, 'marks': marks, 'effect': cells[3]}
for name, dc, marks, effect in [
    ('Deep wound',10,3,'1 HP/day starting tomorrow.'),
    ('Broken bone',12,4,'No physical labor until cured.'),
    ('Snow blindness',10,2,'No navigation or hunting.'),
    ('Frostbite',12,3,'Disadvantage on STR/DEX.')]:
    assert name.lower() in source['seed.md']
    conditions[name] = {'dc':dc, 'marks':marks, 'effect':effect}
assert len(conditions) == 9
rules = {'edition':'0.10','roles':roles,'pregens':pregens,'conditions':conditions,
         'sources': {p:hashlib.sha256(s.encode()).hexdigest() for p,s in source.items()}}
output = '// Generated by tools/build_player_rules.py. Edit the manuscript, then rebuild.\n'
output += 'globalThis.TrailRules = ' + json.dumps(rules, ensure_ascii=False, indent=2) + ';\n'
output += "if (typeof module !== 'undefined') module.exports = globalThis.TrailRules;\n"
target = ROOT/'player/rules.js'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != output:
        sys.exit('Player reference is out of date. Run python3 tools/build_player_rules.py')
    print('PASS: player reference matches 3 canonical sources, 4 pregens, 16 backgrounds, 16 techniques, 9 conditions.')
else:
    target.write_text(output)
    print('Built player/rules.js from the current manuscript.')
